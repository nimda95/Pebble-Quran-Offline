#!/usr/bin/env python3
"""UI languages: builds the watch and phone string tables from lang/<code>.json.

  resources/data/LANG.bin   watch strings of every language (the watch loads one)
  src/c/i18n_ids.h          language and string ids
  src/pkjs/i18n_data.js     settings page strings and language names

Run by the build (wscript). English is the reference: a string missing in
another language falls back to English here, and tools/host/test_lang.js
reports it.

LANG.bin layout (little endian):
  "QLG1", u8 languages, u8 0, u16 strings
  per language: u32 offset, u32 size of its block
  block: u16 offset of each string (from the block start), then the strings, NUL-terminated
"""
import json, os, struct, sys

# Append only: the position is the value saved on the watch (0 = automatic).
LANGS = ['en', 'fr', 'ar', 'tr', 'de', 'nl', 'es', 'id']


def load(root):
    out = {}
    for code in LANGS:
        with open(os.path.join(root, 'lang', code + '.json'), encoding='utf-8') as f:
            out[code] = json.load(f)
    return out


def c_string(s):
    out = '"'
    for b in s.encode('utf-8'):
        c = chr(b)
        if c == '"' or c == '\\':
            out += '\\' + c
        elif 32 <= b < 127:
            out += c
        else:
            out += '\\%03o' % b          # octal escapes never swallow the next character
    return out + '"'


def block(strings):
    n = len(strings)
    data = bytearray()
    offs = []
    for s in strings:
        offs.append(2 * n + len(data))
        data += s.encode('utf-8') + b'\0'
    if 2 * n + len(data) > 0xFFFF:
        raise SystemExit('gen_lang: string block too large')
    return struct.pack('<%dH' % n, *offs) + bytes(data)


def main(root):
    langs = load(root)
    keys = list(langs['en']['watch'].keys())
    page_keys = list(langs['en']['page'].keys())
    blocks = []
    for code in LANGS:
        w = langs[code].get('watch', {})
        missing = [k for k in keys if not w.get(k)]
        if missing:
            sys.stderr.write('gen_lang: %s lacks %s (English used)\n' % (code, ', '.join(missing)))
        blocks.append(block([w.get(k) or langs['en']['watch'][k] for k in keys]))

    head = b'QLG1' + struct.pack('<BBH', len(LANGS), 0, len(keys))
    pos = len(head) + 8 * len(LANGS)
    table = b''
    for b in blocks:
        table += struct.pack('<II', pos, len(b))
        pos += len(b)
    write_if_changed(os.path.join(root, 'resources', 'data', 'LANG.bin'), head + table + b''.join(blocks))

    h = ['// Generated by tools/gen_lang.py from lang/*.json. Do not edit.',
         '#pragma once', '',
         '// UI languages; the value is saved on the watch (append only).',
         'enum { LANG_AUTO, ' + ', '.join('LANG_' + c.upper() for c in LANGS) + ', LANG_N };',
         '#define I18N_CODES { ' + ', '.join(c_string(c) for c in LANGS) + ' }',
         '#define I18N_NAMES { ' + ', '.join(c_string(langs[c]['name']) for c in LANGS) + ' }',
         '#define I18N_BLOCK_MAX %d   // largest language block in LANG.bin' % max(len(b) for b in blocks),
         '', 'enum {']
    h += ['  S_%s,' % k for k in keys]
    h += ['  S_N', '};', '']
    write_if_changed(os.path.join(root, 'src', 'c', 'i18n_ids.h'), '\n'.join(h))

    page = {}
    for code in LANGS:
        p = langs[code].get('page', {})
        page[code] = dict((k, p.get(k) or langs['en']['page'][k]) for k in page_keys)
    js = ('// Generated by tools/gen_lang.py from lang/*.json. Do not edit.\n'
          'module.exports = {\n'
          '  CODES: ' + json.dumps(LANGS) + ',\n'
          '  NAMES: ' + json.dumps([langs[c]['name'] for c in LANGS]) + ',\n'
          '  PAGE: ' + json.dumps(page, indent=1, sort_keys=False) + '\n'
          '};\n')
    write_if_changed(os.path.join(root, 'src', 'pkjs', 'i18n_data.js'), js)


def write_if_changed(path, data):
    mode = 'b' if isinstance(data, bytes) else ''
    if os.path.exists(path):
        with open(path, 'r' + mode) as f:
            if f.read() == data:
                return
    with open(path, 'w' + mode) as f:
        f.write(data)


if __name__ == '__main__':
    here = os.path.dirname(os.path.abspath(__file__))
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(here))
