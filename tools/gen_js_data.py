#!/usr/bin/env python3
"""Embeds the renderer data files into src/pkjs/data_blob.js (base64) so the
phone can render pages with exactly the same data as the watch."""
import base64, os, sys, zlib

FILES = ['TEXT', 'LEX', 'TUP15', 'TUP20', 'TUP26', 'TUP28', 'TUP32',
         'ATL15', 'ATL20', 'ATL26', 'ATL28', 'ATL32', 'META']   # LINES is per screen width: not shared

def main(data_dir, out_path):
    parts = ['// Generated by tools/gen_js_data.py from resources/data. Do not edit.\n',
             'module.exports = {\n']
    crc = 0
    for name in FILES:
        with open(os.path.join(data_dir, name + '.bin'), 'rb') as f:
            raw = f.read()
        crc = zlib.crc32(raw, crc)
        parts.append("  %s: '%s',\n" % (name, base64.b64encode(raw).decode('ascii')))
    crc &= 0x7FFFFFFF
    parts.append('  VERSION: %d\n' % crc)
    parts.append('};\n')
    write_if_changed(os.path.join(os.path.dirname(out_path), '..', 'c', 'data_version.h'),
                     '// Generated by tools/gen_js_data.py. Do not edit.\n'
                     '#pragma once\n#define DATA_VERSION %dUL\n' % crc)
    write_if_changed(out_path, ''.join(parts))


def write_if_changed(path, text):
    if os.path.exists(path):
        with open(path) as f:
            if f.read() == text:
                return
    with open(path, 'w') as f:
        f.write(text)

if __name__ == '__main__':
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.dirname(here)
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, 'resources', 'data'),
         sys.argv[2] if len(sys.argv) > 2 else os.path.join(root, 'src', 'pkjs', 'data_blob.js'))
