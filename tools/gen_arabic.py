#!/usr/bin/env python3
"""Builds the Arabic (Unicode) text used by the system-font reading mode.

Inputs (download once):
  ara-quransimple.min.json  https://cdn.jsdelivr.net/gh/fawazahmed0/quran-api@1/editions/ara-quransimple.min.json
  surahs.json               https://api.alquran.cloud/v1/surah
Outputs:
  src/pkjs/arabic_blob.js   compact text for the phone (word dictionary + word indices)
  src/c/names_ar.c          surah names and the basmala for the watch (UTF-8)

Usage: gen_arabic.py <ara-quransimple.min.json> <surahs.json>
"""
import base64, collections, json, os, sys, unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIACRITICS = set(range(0x064B, 0x0660)) | {0x0670} | set(range(0x0610, 0x061B)) | set(range(0x06D6, 0x06EE))
BASMALA_WORDS = 4


def keep(c):
    """The system font has no Quranic annotation marks: drop them (keep rub el hizb and sajdah)."""
    o = ord(c)
    if o == 0xFEFF:
        return False
    if 0x06D6 <= o <= 0x06ED and o not in (0x06DE, 0x06E9):
        return False
    if 0x08F0 <= o <= 0x08FF:
        return False
    return True


def clean(text):
    text = ''.join(c for c in text if keep(c)).replace('ٱ', 'ا')
    return ' '.join(text.split())


def bare(word):
    # compose first so alef + madda/hamza marks become one letter, then drop marks and tatweel
    word = unicodedata.normalize('NFC', word)
    return ''.join(c for c in word if ord(c) not in DIACRITICS and c != '\u0640')


def main(quran_path, surahs_path):
    verses = json.load(open(quran_path, encoding='utf-8'))['quran']
    assert len(verses) == 6236
    surahs = json.load(open(surahs_path, encoding='utf-8'))['data']
    assert len(surahs) == 114

    basmala = None
    ayahs = []
    for v in verses:
        t = clean(v['text'])
        words = t.split(' ')
        if v['verse'] == 1 and bare(words[0]) == 'بسم':
            if v['chapter'] == 1:
                basmala = t
            elif v['chapter'] != 9:
                t = ' '.join(words[BASMALA_WORDS:])   # the basmala is shown as its own line
        ayahs.append(t)
    assert basmala

    # dictionary of words, most frequent first; text as varint word indices
    freq = collections.Counter(w for a in ayahs for w in a.split(' ') if w)
    vocab = [w for w, _ in freq.most_common()]
    index = {w: i for i, w in enumerate(vocab)}
    chars = sorted(set(''.join(vocab)))
    assert len(chars) < 255
    cmap = {c: i + 1 for i, c in enumerate(chars)}
    vbytes = bytearray()
    for w in vocab:
        vbytes += bytes(cmap[c] for c in w) + b'\0'
    tbytes, counts = bytearray(), bytearray()
    for a in ayahs:
        ws = [w for w in a.split(' ') if w]
        assert len(ws) < 256
        counts.append(len(ws))
        for w in ws:
            i = index[w]
            if i < 0x80:
                tbytes.append(i)
            else:
                assert i < 0x8000
                tbytes += bytes((0x80 | (i >> 8), i & 0xFF))
    js = ('// Generated by tools/gen_arabic.py from the Tanzil "Quran Simple" text. Do not edit.\n'
          'module.exports = {\n'
          '  CHARS: %s,\n  VOCAB: \'%s\',\n  TEXT: \'%s\',\n  COUNTS: \'%s\'\n};\n') % (
        json.dumps(''.join(chars)), base64.b64encode(bytes(vbytes)).decode(),
        base64.b64encode(bytes(tbytes)).decode(), base64.b64encode(bytes(counts)).decode())
    with open(os.path.join(ROOT, 'src', 'pkjs', 'arabic_blob.js'), 'w', encoding='utf-8') as f:
        f.write(js)

    def cstr(s):
        return '"' + ''.join('\\x%02x' % b for b in s.encode('utf-8')) + '"'
    names = []
    for s in surahs:
        n = bare(s['name']).replace('ٱ', 'ا').split(' ')
        if n[0] == 'سورة':   # drop the word "surah"
            n = n[1:]
        names.append(' '.join(n))
    with open(os.path.join(ROOT, 'src', 'c', 'names_ar.c'), 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/gen_arabic.py. Do not edit.\n#include "names_ar.h"\n\n')
        f.write('// %s\nconst char *const NAMES_AR_BASMALA = %s;\n\n' % (basmala, cstr(basmala)))
        f.write('const char *const NAMES_AR[114] = {\n')
        for i, n in enumerate(names):
            f.write('  %s,  // %d %s\n' % (cstr(n), i + 1, n))
        f.write('};\n')
    print('vocab %d words, %d chars; text %d bytes; js %d bytes' % (
        len(vocab), len(chars), len(tbytes), len(js)))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
